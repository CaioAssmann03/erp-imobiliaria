from typing import final

from django.contrib import admin
from django.http import HttpRequest
from unfold.admin import ModelAdmin, TabularInline

from apps.core.scoping import CompanyScopedAdminMixin

from .models import BillingDocument, BillingDocumentItem, BillingDocumentPdf, BillingPlan, BillingPlanItem, BillingRun


@final
class BillingPlanItemInline(CompanyScopedAdminMixin, TabularInline):
    model = BillingPlanItem
    extra = 0
    ordering = ("position",)


@final
@admin.register(BillingPlan)
class BillingPlanAdmin(CompanyScopedAdminMixin, ModelAdmin):
    list_display = ("name", "condominium", "active", "start_month", "end_month")
    search_fields = ("name", "condominium__name")
    list_filter = ("active", "condominium")
    inlines = (BillingPlanItemInline,)


@final
class BillingDocumentItemInline(CompanyScopedAdminMixin, TabularInline):
    model = BillingDocumentItem
    extra = 0
    ordering = ("position",)
    can_delete = False

    def has_add_permission(self, request: HttpRequest, obj: BillingDocument | None = None) -> bool:
        return False

    def has_change_permission(self, request: HttpRequest, obj: BillingDocument | None = None) -> bool:
        return False


@final
@admin.register(BillingDocument)
class BillingDocumentAdmin(CompanyScopedAdminMixin, ModelAdmin):
    """Read-only: documents are issued by the monthly issuance and only cancelled through the API."""

    list_display = ("unit", "payer", "reference_month", "due_date", "amount", "status")
    search_fields = ("unit__name", "unit__condominium__name", "payer__name")
    list_filter = ("status", "reference_month")
    inlines = (BillingDocumentItemInline,)

    def has_add_permission(self, request: HttpRequest) -> bool:
        return False

    def has_change_permission(self, request: HttpRequest, obj: BillingDocument | None = None) -> bool:
        return False

    def has_delete_permission(self, request: HttpRequest, obj: BillingDocument | None = None) -> bool:
        return False


@final
@admin.register(BillingRun)
class BillingRunAdmin(CompanyScopedAdminMixin, ModelAdmin):
    """Read-only: runs are recorded by the monthly issuance."""

